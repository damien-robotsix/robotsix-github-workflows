"""Tests for scripts/uv_with_pins.py."""

from __future__ import annotations

import datetime as dt
import importlib.util
import io
import sys
from pathlib import Path

import pytest

_scripts_dir = Path(__file__).resolve().parent.parent / "scripts"
_spec = importlib.util.spec_from_file_location(
    "uv_with_pins", _scripts_dir / "uv_with_pins.py"
)
assert _spec is not None and _spec.loader is not None
_module = importlib.util.module_from_spec(_spec)
# Register before exec: @dataclass resolves its module via sys.modules.
sys.modules[_spec.name] = _module
_spec.loader.exec_module(_module)

build = _module.build
main = _module.main
parse_locked = _module.parse_locked
FLIP_DATE = _module.FLIP_DATE

BEFORE_FLIP = FLIP_DATE - dt.timedelta(days=1)

# Shape of `uv export --frozen --no-hashes --no-emit-project` output for a
# fixture project whose lock pins pytest 9.1.1 (the 2026-10-28 incident).
LOCK_WITHOUT_PLUGINS = """\
# This file was autogenerated by uv via the following command:
#    uv export --frozen --no-hashes --no-emit-project
anyio==4.11.0
    # via fastapi
colorama==0.4.6 ; sys_platform == 'win32'
    # via pytest
coverage==7.15.4
pluggy==1.6.0
    # via pytest
pytest==9.1.1
pytest-asyncio==1.4.0
"""

LOCK_WITH_PLUGINS = LOCK_WITHOUT_PLUGINS + "pytest-cov==7.0.0\npytest_xdist==3.7.0\n"


def _pairs(args: list[str]) -> list[str]:
    assert args[::2] == ["--with"] * (len(args) // 2)
    return args[1::2]


class TestParseLocked:
    def test_markers_comments_and_normalization(self) -> None:
        locked = parse_locked(LOCK_WITH_PLUGINS)
        assert locked["pytest"] == "9.1.1"
        assert locked["colorama"] == "0.4.6"
        assert locked["pytest-xdist"] == "3.7.0"
        assert "# via pytest" not in locked

    def test_extras_and_line_continuation(self) -> None:
        locked = parse_locked("Bandit[toml]==1.9.4 \\\n")
        assert locked == {"bandit": "1.9.4"}


class TestBuild:
    def test_overlay_pins_locked_pytest(self) -> None:
        res = build(LOCK_WITHOUT_PLUGINS, BEFORE_FLIP)
        pins = _pairs(res.args)
        assert "pytest==9.1.1" in pins
        assert "pytest-asyncio==1.4.0" in pins
        assert "pluggy==1.6.0" in pins
        assert "coverage==7.15.4" in pins
        assert not any(p.startswith("pytest==") and p != "pytest==9.1.1" for p in pins)

    def test_missing_plugins_warn_before_flip(self) -> None:
        res = build(LOCK_WITHOUT_PLUGINS, BEFORE_FLIP)
        pins = _pairs(res.args)
        assert "pytest-xdist==3.8.0" in pins
        assert "pytest-cov==7.1.0" in pins
        assert res.errors == []
        assert len(res.warnings) == 2

    def test_missing_plugins_fail_on_flip(self) -> None:
        res = build(LOCK_WITHOUT_PLUGINS, FLIP_DATE)
        assert len(res.errors) == 2
        assert res.warnings == []

    def test_locked_plugins_use_lock_versions_no_warning(self) -> None:
        res = build(LOCK_WITH_PLUGINS, FLIP_DATE)
        pins = _pairs(res.args)
        assert "pytest-xdist==3.7.0" in pins
        assert "pytest-cov==7.0.0" in pins
        assert res.warnings == [] and res.errors == []

    def test_unlocked_optional_packages_not_pinned(self) -> None:
        res = build("pytest==9.1.1\n", BEFORE_FLIP)
        pins = _pairs(res.args)
        assert not any(p.startswith(("pytest-asyncio==", "coverage==")) for p in pins)


class TestMain:
    def test_prints_one_token_per_line(
        self, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
    ) -> None:
        monkeypatch.setattr(sys, "stdin", io.StringIO(LOCK_WITH_PLUGINS))
        assert main(["--today", BEFORE_FLIP.isoformat()]) == 0
        out = capsys.readouterr().out.splitlines()
        assert out[:2] == ["--with", "pytest==9.1.1"]

    def test_error_after_flip_exits_1(
        self, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
    ) -> None:
        monkeypatch.setenv("GITHUB_ACTIONS", "true")
        monkeypatch.setattr(sys, "stdin", io.StringIO(LOCK_WITHOUT_PLUGINS))
        assert main(["--today", FLIP_DATE.isoformat()]) == 1
        captured = capsys.readouterr()
        assert captured.out == ""
        assert "::error::pytest-xdist is not in uv.lock" in captured.err
